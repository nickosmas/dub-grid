import { networkInterfaces } from "os";
import { readFileSync, writeFileSync } from "fs";
import { resolve } from "path";

const repoRoot = resolve(new URL(".", import.meta.url).pathname, "..");
const rootEnvPath = resolve(repoRoot, ".env.local");
const mobileEnvPath = resolve(repoRoot, "apps/mobile/.env.local");

function parseEnvFile(path) {
  const content = readFileSync(path, "utf8");
  const values = {};

  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;

    const separator = trimmed.indexOf("=");
    if (separator <= 0) continue;

    const key = trimmed.slice(0, separator).trim();
    let value = trimmed.slice(separator + 1).trim();

    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    values[key] = value;
  }

  return values;
}

function isLoopbackHost(hostname) {
  return (
    hostname === "localhost" ||
    hostname === "127.0.0.1" ||
    hostname === "0.0.0.0" ||
    hostname === "::1"
  );
}

function isPrivateIpv4Address(address) {
  if (/^10\./.test(address)) return true;
  if (/^192\.168\./.test(address)) return true;

  const match = address.match(/^172\.(\d+)\./);
  if (!match) return false;

  const secondOctet = Number(match[1]);
  return secondOctet >= 16 && secondOctet <= 31;
}

function pickLanIpAddress() {
  const interfaces = networkInterfaces();

  for (const addresses of Object.values(interfaces)) {
    for (const address of addresses ?? []) {
      if (
        address.family === "IPv4" &&
        !address.internal &&
        isPrivateIpv4Address(address.address)
      ) {
        return address.address;
      }
    }
  }

  return null;
}

function toLanUrl(candidate, lanIp) {
  const parsed = new URL(candidate);
  if (!isLoopbackHost(parsed.hostname)) {
    throw new Error(
      `Expected a local loopback URL but received ${candidate}. Run \`npm run use:local\` first so the repo points at local Supabase.`,
    );
  }

  parsed.hostname = lanIp;
  return parsed.toString().replace(/\/$/, "");
}

function getWebBaseUrl(env, lanIp) {
  const siteUrl = env.NEXT_PUBLIC_SITE_URL?.trim() || "http://localhost:3000";
  const parsed = new URL(siteUrl);

  if (!isLoopbackHost(parsed.hostname)) {
    throw new Error(
      `Expected NEXT_PUBLIC_SITE_URL to be local but received ${siteUrl}. Update the repo root .env.local before generating the mobile local env.`,
    );
  }

  parsed.hostname = lanIp;
  return parsed.toString().replace(/\/$/, "");
}

function main() {
  const requestedIp = process.argv[2] || process.env.DUBGRID_LAN_IP || "";
  const lanIp = requestedIp || pickLanIpAddress();

  if (!lanIp) {
    throw new Error(
      "Could not detect a private LAN IP automatically. Re-run with `npm run use:mobile:local -- 192.168.x.x` or set DUBGRID_LAN_IP.",
    );
  }

  const env = parseEnvFile(rootEnvPath);
  const supabaseUrl = env.NEXT_PUBLIC_SUPABASE_URL?.trim();
  const supabaseAnonKey = env.NEXT_PUBLIC_SUPABASE_ANON_KEY?.trim();

  if (!supabaseUrl || !supabaseAnonKey) {
    throw new Error(
      `Missing NEXT_PUBLIC_SUPABASE_URL or NEXT_PUBLIC_SUPABASE_ANON_KEY in ${rootEnvPath}. Run \`npm run use:local\` first.`,
    );
  }

  const mobileSupabaseUrl = toLanUrl(supabaseUrl, lanIp);
  const mobileApiBaseUrl = getWebBaseUrl(env, lanIp);
  const output = [
    "# DubGrid mobile Expo environment",
    "#",
    "# Generated by `npm run use:mobile:local`.",
    "# This file is intentionally phone-safe for local testing only.",
    "# If you want the hosted backend instead, run `npm run use:mobile:remote`.",
    "",
    `EXPO_PUBLIC_SUPABASE_URL=${mobileSupabaseUrl}`,
    `EXPO_PUBLIC_SUPABASE_ANON_KEY=${supabaseAnonKey}`,
    `EXPO_PUBLIC_API_BASE_URL=${mobileApiBaseUrl}`,
    "",
  ].join("\n");

  writeFileSync(mobileEnvPath, output, "utf8");

  console.log(`Wrote ${mobileEnvPath}`);
  console.log(`  Supabase: ${mobileSupabaseUrl}`);
  console.log(`  Web API:  ${mobileApiBaseUrl}`);
  console.log("Next steps:");
  console.log("  1. Start local Supabase: npx supabase start");
  console.log("  2. Start the web app on your LAN: npm run dev:web:lan");
  console.log("  3. Start Expo: npm run dev:mobile");
}

try {
  main();
} catch (error) {
  const message = error instanceof Error ? error.message : String(error);
  console.error(`[use-mobile-local] ${message}`);
  process.exit(1);
}
